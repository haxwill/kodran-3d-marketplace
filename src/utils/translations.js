export const autoTranslateString = (text, targetLang = 'TR') => {
  if (!text || typeof text !== 'string') return text || '';
  if (targetLang !== 'EN') return text;

  const lower = text.toLowerCase().trim();
  if (dictionaryMap[lower]) {
    return dictionaryMap[lower];
  }

  // Common replacements in text
  let translated = text;
  for (const [trWord, enWord] of Object.entries(dictionaryMap)) {
    const regex = new RegExp(`\\b${trWord}\\b`, 'gi');
    translated = translated.replace(regex, enWord);
  }

  return translated;
};

export const getLocalizedText = (value, language = 'TR') => {
  if (!value) return '';
  if (typeof value === 'object') {
    return value[language] || value.TR || value.EN || Object.values(value)[0] || '';
  }
  if (language === 'EN') {
    return autoTranslateString(String(value), 'EN');
  }
  return String(value);
};

